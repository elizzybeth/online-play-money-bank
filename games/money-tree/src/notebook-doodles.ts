export function notebookSketches(page: number) {
  return [0, 1, 2].map((slot) => ({
    path: sketches[(page * 5 + slot * 3) % sketches.length],
    x: 8 + slot * 48,
    y: 8 + ((page + slot) % 3) * 9,
    rotation: ((page * 7 + slot * 11) % 19) - 9,
  }));
}
